  await page.addInitScript(() => {
    Object.defineProperty(navigator, 'userAgent', { get: () => 'Mozilla/5.0 (iPhone) AppleWebKit/605.1.15 Mobile Safari/604.1' })
    Object.defineProperty(navigator, 'maxTouchPoints', { get: () => 5 })
  })
  await page.reload()
  await page.getByText('Use your device’s volume buttons', { exact: true }).waitFor()
  assert.equal(await page.getByRole('slider', { name: 'Volume', exact: true }).count(), 0)
  checks.push('iOS capability emulation shows physical-volume guidance instead of an ineffective slider (Chromium, not physical Safari)')
  assert.ok((await page.getByRole('heading', {name:'TEST — simulated Spotify (no sound)',exact:true}).boundingBox()).width >= 150)
