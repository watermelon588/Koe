-- Koe app chat in Neon (ACCOUNTS_SPEC.md, task 5): messages, voice notes and push subscriptions survive
-- Render restarts and belong to one owner each. Additive and rerunnable; same rules as 001:
-- backend-only tables, RLS on, no PUBLIC privileges. Run: python -m scripts.migrate_store (from backend/).
begin;

create table if not exists public.koe_app_messages (
  id bigint generated by default as identity primary key, owner_id text not null,
  ts text not null, role text not null check (role in ('you','koe','alert')),
  text text not null default '', voice text, action_id text, action_status text
);
create index if not exists koe_app_messages_owner_id on public.koe_app_messages(owner_id, id);

-- A voice note is at most ~3 MB (MAX_VOICE_BYTES); Koe's spoken replies are about 48 KB per second.
create table if not exists public.koe_app_voice (
  name text primary key, owner_id text not null, created text not null, audio bytea not null
);

create table if not exists public.koe_app_push (
  endpoint text primary key, owner_id text not null, subscription text not null
);
create index if not exists koe_app_push_owner on public.koe_app_push(owner_id);

alter table public.koe_app_messages enable row level security;
alter table public.koe_app_voice enable row level security;
alter table public.koe_app_push enable row level security;
revoke all on public.koe_app_messages, public.koe_app_voice, public.koe_app_push from public;

commit;
