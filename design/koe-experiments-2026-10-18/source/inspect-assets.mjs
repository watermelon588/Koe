import {readdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const root=process.cwd();
const out=path.join(root,'design/koe-experiments-2026-10-18');
const dirs=['frontend/assets/mascot','frontend/assets','frontend/assets/mascot reference'];
const files=[];
for(const d of dirs)for(const f of (await readdir(d)).sort())if(/\.(png|jpe?g)$/i.test(f))files.push(path.join(root,d,f));
const html=`<html><style>body{margin:0;padding:20px;background:#d9dfdb;font:12px Arial}.grid{display:grid;grid-template-columns:repeat(6,1fr);gap:14px}figure{margin:0;background:#eef0ed;padding:8px}img{width:100%;height:205px;object-fit:contain}figcaption{height:32px;font-size:10px;overflow-wrap:anywhere}</style><div class="grid">${files.map((f,i)=>`<figure><img src="${pathToFileURL(f).href}"><figcaption>${i+1} · ${path.basename(f)}</figcaption></figure>`).join('')}</div></html>`;
await writeFile(path.join(out,'source/asset-atlas.html'),html);
await writeFile(path.join(out,'source/asset-index.json'),JSON.stringify(files,null,2));
const {chromium}=await import(pathToFileURL('C:/Users/Rohit Maity/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs').href);
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1500,height:1000}});
await page.goto(pathToFileURL(path.join(out,'source/asset-atlas.html')).href);
await page.evaluate(()=>Promise.all([...document.images].map(i=>i.decode())));
await page.screenshot({path:path.join(out,'source/asset-atlas.png'),fullPage:true});
await browser.close();
console.log('Inspected asset catalog:',files.length,'images');
